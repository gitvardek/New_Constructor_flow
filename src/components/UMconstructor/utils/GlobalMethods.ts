// Чистые функции по геометрии сетки УМ: то, что нужно сразу нескольким модулям
// (движок, 2D-слой, панели) и зависит от параметров модуля, а не от констант.
// Без импортов из движка — чтобы файл можно было звать откуда угодно.

// На сколько фасад ящика может свисать ниже дна области: дно он закрывает
// целиком, не доходя 2 мм до нижнего края модуля. С опцией «Без дна» дно
// области уже совпадает с краем, и те же 2 мм фасад обязан уйти внутрь.
export const getBottomFasadeOverhang = (moduleThickness: number = 0, noBottom?: boolean): number =>
    (noBottom ? 0 : moduleThickness) - 2;
